package com.coder.skulens.engine

import android.graphics.Bitmap

/**
 * Generic contract for the visual search pipeline (Strategy Pattern).
 *
 * Decouples image processing, feature extraction, and similarity scoring from any
 * specific underlying machine learning framework (e.g., MediaPipe, TFLite, ONNX, PyTorch).
 *
 * Implementing this strategy ensures that future model changes (e.g., swapping ViT backbones
 * or changing detection networks) require zero modifications to the core data repository or UI layers.
 */
interface IVisualSearchPipeline {

    /**
     * The fixed dimensionality of the feature vector generated by this pipeline.
     * Must match the storage schema (e.g., ObjectBox HNSW index dimension).
     */
    val embeddingDimension: Int

    /**
     * Executes the end-to-end visual search pipeline on the given image:
     * 1. Stage 1: Detects target clothing bounding box and crops out background noise.
     * 2. Stage 2: Prepares tensor and extracts the L2-normalized ViT feature vector.
     *
     * @param bitmap The source image from camera or gallery.
     * @return L2-normalized FloatArray of size [embeddingDimension], or null if processing fails.
     */
    fun extractEmbedding(bitmap: Bitmap): FloatArray?

    /**
     * Computes the cosine similarity between two feature vectors.
     *
     * Since both vectors are L2-normalized (unit length):
     *   cosine_similarity(u, v) = (u . v) / (||u|| * ||v||) = u . v
     *
     * @param vectorA First feature vector.
     * @param vectorB Second feature vector.
     * @return Cosine similarity score in range [-1.0, 1.0].
     */
    fun calculateCosineSimilarity(vectorA: FloatArray, vectorB: FloatArray): Float

    /**
     * Max-Score Matching Strategy:
     * Compares a query vector against all registered angle vectors of a single product item
     * (e.g., front, back, side angles) and returns the maximum similarity score.
     *
     * Rationale: Averaging scores across angles penalizes products because a front view
     * query will naturally have low similarity to a back view angle. Max-score ensures
     * that a strong match on any single angle correctly identifies the product.
     *
     * @param queryVector The feature vector extracted from the search query photo.
     * @param candidateVectors The list of stored angle vectors for a candidate product.
     * @return The highest cosine similarity score among the candidate vectors, or 0.0f if empty.
     */
    fun maxScoreMatch(queryVector: FloatArray, candidateVectors: List<FloatArray>): Float
}
